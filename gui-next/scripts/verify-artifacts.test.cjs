const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { verify } = require('./verify-artifacts.cjs');
test('packaging refuses unpinned, missing and changed binaries and checks packaged copies', async t => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vssc-artifacts-'));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const artifacts = ['artifacts/driver/TimoxVasio.dll', 'artifacts/backend/TimoxVirtualAsioEngine.exe', 'artifacts/backend/PwarAsioClient.exe'].map(path => ({path, revision: 'test-revision', sha256: crypto.createHash('sha256').update('fixture').digest('hex')}));
    const schemas = ['api/openapi-v1.json', 'api/schemas/api-v1.json'].map(name => ({path:name, sha256: artifacts[0].sha256}));
    fs.mkdirSync(path.join(root, 'api/schemas'), {recursive:true});
    for(const item of schemas) fs.writeFileSync(path.join(root, item.path), 'fixture');
    const writeLock = () => fs.writeFileSync(path.join(root, 'artifacts.lock.json'), JSON.stringify({artifacts, schemas}));
    writeLock();
    assert.throws(() => verify(root), /ENOENT/);
    fs.mkdirSync(path.join(root, 'artifacts/backend'), {recursive:true});
    fs.mkdirSync(path.join(root, 'artifacts/driver'), {recursive:true});
    for(const item of artifacts) fs.writeFileSync(path.join(root, item.path), 'fixture');
    verify(root);
    fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ version: '0.2.0-alpha.1' }));
    await assert.rejects(require('./before-pack.cjs')({packager:{info:{appDir:root}}}), /Release metadata/);
    const saved = artifacts[0].sha256; artifacts[0].sha256 = null; writeLock();
    assert.throws(() => verify(root), /Unpinned/);
    artifacts[0].sha256 = saved; writeLock();
    fs.writeFileSync(path.join(root, artifacts[0].path), 'changed');
    assert.throws(() => verify(root), /hash mismatch/);
    fs.writeFileSync(path.join(root, artifacts[0].path), 'fixture');
    assert.throws(() => verify(root, true), /ENOENT/);
    fs.mkdirSync(path.join(root, 'dist/win-unpacked/resources/backend'), {recursive:true});
    for(const item of artifacts) fs.copyFileSync(path.join(root, item.path), path.join(root, 'dist/win-unpacked/resources/backend', path.basename(item.path)));
    fs.mkdirSync(path.join(root, 'dist/win-unpacked/resources/backend/schemas'), {recursive:true});
    for(const item of schemas) fs.copyFileSync(path.join(root, item.path), path.join(root, 'dist/win-unpacked/resources/backend', item.path.slice(4)));
    verify(root, true);
    fs.writeFileSync(path.join(root, 'dist/win-unpacked/resources/backend/openapi-v1.json'), 'changed');
    assert.throws(() => verify(root, true), /Packaged schema hash mismatch/);
    fs.writeFileSync(path.join(root, 'artifacts.lock.json'), JSON.stringify({artifacts}));
    assert.throws(() => verify(root), /Unpinned schema/);
    fs.writeFileSync(path.join(root, 'artifacts.lock.json'), JSON.stringify({artifacts, schemas: []}));
    assert.throws(() => verify(root), /Unpinned schema/);
});

